#!/usr/bin/env python3
"""Builds public/js/recipes-morocco.js (the built-in Moroccan recipes) from JSON files.

    python3 tools/build-moroccan.py tools/recipes-morocco/*.json

Each JSON file is an array of recipes:
  {id: "ma01", title, en, cat, pic, serves, time, ingredients: [{name, qty}],
   steps: [{text, minutes}], sources: [url, ...]}
The pictures are public/img/recipes/<pic>.svg.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'public', 'js', 'recipes-morocco.js')
CATS = {'Soup', 'Vegetarian', 'Breakfast', 'Chicken', 'Lamb', 'Beef', 'Seafood', 'Dessert'}

recipes, problems = [], []
for path in sys.argv[1:]:
    for r in json.load(open(path, encoding='utf-8')):
        rid = r.get('id', '?')
        for k in ('id', 'title', 'en', 'cat', 'pic', 'ingredients', 'steps'):
            if not r.get(k): problems.append(f'{rid}: missing {k}')
        if r.get('cat') not in CATS: problems.append(f'{rid}: unknown cat {r.get("cat")}')
        if not re.fullmatch(r'ma\d{2,3}', rid): problems.append(f'{rid}: bad id')
        if not os.environ.get('SKIP_PICS') and not os.path.exists(os.path.join(ROOT, 'public', 'img', 'recipes', str(r.get('pic')) + '.svg')):
            problems.append(f'{rid}: no picture {r.get("pic")}.svg')
        steps = []
        for s in r.get('steps', []):
            m = s.get('minutes')
            m = int(round(float(m))) if isinstance(m, (int, float)) and 1 <= m <= 600 else None
            steps.append({'text': str(s.get('text', '')).strip(), 'minutes': m})
        recipes.append({
            'id': rid, 'title': r['title'].strip(), 'en': r.get('en', '').strip(), 'cat': r['cat'], 'pic': r['pic'],
            'serves': r.get('serves') or None, 'time': r.get('time') or None,
            'ingredients': [{'name': str(x.get('name', '')).strip(), 'qty': str(x.get('qty', '') or '').strip()} for x in r['ingredients'] if x.get('name')],
            'steps': [s for s in steps if s['text']],
            'sources': [u for u in r.get('sources', []) if isinstance(u, str) and u.startswith('http')][:3],
        })
ids = [r['id'] for r in recipes]
if len(ids) != len(set(ids)): problems.append('duplicate ids')
if problems:
    print('\n'.join(problems)); sys.exit(1)
recipes.sort(key=lambda r: r['id'])

HEAD = '''// «وصفات مغربية»: classic Moroccan home recipes built into the app (TheMealDB has only a handful).
// Each one was put together from Moroccan cooks' published recipes (the "sources" field) and
// written in simple Arabic for the kitchen screen. Generated by tools/build-moroccan.py — edit the
// JSON and rebuild rather than this file. Shared by the server (src/recipes.js) and the previews.
'''
TAIL = '''
const PIC = (p) => '/img/recipes/' + p + '.svg';
// The shape the frame and the panel use (as for TheMealDB recipes, already in Arabic).
export const moroccanRecipe = (r) => ({
  id: r.id, title: r.title, area: 'Moroccan', category: r.cat, thumb: PIC(r.pic), lang: 'ar',
  serves: r.serves, time: r.time, ingredients: r.ingredients, steps: r.steps, sources: r.sources, builtin: true,
});
export const moroccanCard = (r) => ({ id: r.id, name: r.en || r.title, ar: r.title, thumb: PIC(r.pic), builtin: true });
export const moroccanById = (id) => MOROCCAN.find((r) => r.id === String(id)) || null;
// The built-in recipes on a shelf: all of them under «مغربية», and by kind of dish elsewhere.
export const moroccanFor = (shelf) => !shelf ? [] : shelf.kind === 'a' ? (shelf.id === 'Moroccan' ? MOROCCAN : []) : MOROCCAN.filter((r) => r.cat === shelf.id);
// A search: in Arabic or by the usual name («tajine», «harira»).
const norm = (s) => String(s || '').toLowerCase().replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي').replace(/[\\u064B-\\u0652]/g, '').replace(/[^a-z0-9\\u0600-\\u06FF ]+/g, ' ').replace(/\\s+/g, ' ').trim();
export function moroccanMatching(q) {
  const n = norm(q);
  if (!n) return [];
  const words = n.split(' ');
  return MOROCCAN.filter((r) => {
    const hay = norm(r.title + ' ' + r.en + ' ' + r.ingredients.map((x) => x.name).join(' '));
    const name = norm(r.title + ' ' + r.en);
    return words.every((w) => hay.includes(w)) || name.includes(n);
  }).sort((a, b) => (norm(b.title + ' ' + b.en).includes(n) ? 1 : 0) - (norm(a.title + ' ' + a.en).includes(n) ? 1 : 0));
}
'''
with open(OUT, 'w', encoding='utf-8') as f:
    f.write(HEAD + 'export const MOROCCAN = ' + json.dumps(recipes, ensure_ascii=False, indent=1) + ';\n' + TAIL)
print(f'{len(recipes)} recipes → {os.path.relpath(OUT, ROOT)}')
