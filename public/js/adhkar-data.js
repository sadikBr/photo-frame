// The list for one session: 'm' (morning) or 'e' (evening).
export function adhkarFor(set) {
  return ADHKAR.filter((a) => !a.only || a.only === set).map((a) => ({ title: a.title || '', n: a.n, ref: a.ref || '', t: a.t || a[set] }));
}

