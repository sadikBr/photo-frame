// dayNumber: days since 1970 (local). Even days a verse, odd days a hadith.
export function verseOfDay(dayNumber) {
  const i = Math.floor(dayNumber / 2);
  if (dayNumber % 2 === 0) { const v = VERSES[i % VERSES.length]; return { kind: 'verse', text: v[0], ref: v[1] }; }
  const v = HADITH[i % HADITH.length];
  return { kind: 'hadith', text: v[0], ref: v[1] };
}
